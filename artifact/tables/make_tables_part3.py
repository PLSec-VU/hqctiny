#!/usr/bin/env python3
"""Builds the part 3 tables from the stored WAN JSON files and McTiny stderr files.
Usage: make_tables_part3.py > tables_part3.md   (set RESULTS_DIR)
"""
import glob
import gzip
import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from results_dir import results_dir

HERE = results_dir() / "part3"
OLD = results_dir() / "part1"
WAN_NAMES = ["wan_profiles", "wan_loss_low", "wan_ge", "wan_loss_high"]
CAP_S = 120.0
TAIL_S = 100.0
GAP_S = 5.0


def pct(values, p):
    sv = sorted(values)
    k = (len(sv) - 1) * p
    f = int(k)
    c = min(f + 1, len(sv) - 1)
    return sv[f] + (sv[c] - sv[f]) * (k - f)


def stats3(values):
    return f"{st.median(values):.3f} / {pct(values, 0.95):.3f} / {max(values):.3f}" if values else "-"


def find(base, name):
    paths = sorted(glob.glob(str(base / "*" / "raw" / f"{name}.json")))
    return Path(paths[-1]) if paths else None


def load(base, name):
    path = find(base, name)
    return (path, json.load(open(path))["results"]) if path else (None, {})


def values(rows, key):
    return [r[key] for r in rows if r.get("ok") and r.get(key) is not None]


def cell_order(keys):
    seen = []
    for key in keys:
        cell = key.split("/", 1)[1]
        if cell not in seen:
            seen.append(cell)
    return seen


def table(head, rows):
    print("| " + " | ".join(head) + " |")
    print("|" + "---|" * len(head))
    for row in rows:
        print("| " + " | ".join(str(x) for x in row) + " |")
    print()


def events(stderr_gz):
    out = []
    for line in gzip.decompress(Path(stderr_gz).read_bytes()).decode(errors="replace").splitlines():
        if line[:2] in ("> ", "< "):
            fields = line.split()
            out.append((float(fields[1]), "sent" if fields[0] == ">" else "received", int(fields[2])))
    return out


def tail_report(directory, name, key, rep_index, row):
    evs = events(directory / "raw" / row["stderr_file"])
    t0 = evs[0][0]
    gaps = sorted(((b[0] - a[0], a[0] - t0, a[1], b[1]) for a, b in zip(evs, evs[1:])), reverse=True)
    big = [g for g in gaps if g[0] >= GAP_S]
    sent_after = sum(1 for e in evs if e[1] == "sent")
    recv = [e for e in evs if e[1] == "received"]
    text = "; ".join(f"{g[0]:.1f} s idle after t={g[1]:.1f} s (last {g[2]}, next {g[3]})" for g in sorted(big, key=lambda g: g[1]))
    return [key, rep_index, f"{row['network_s']:.1f}", sent_after, len(recv), text or "no idle gap >= 5 s"]


def main():
    new = {}
    dirs = {}
    for name in WAN_NAMES:
        path, data = load(HERE, name)
        new[name] = data
        dirs[name] = path.parent.parent if path else None
    old = {name: load(OLD, name)[1] for name in WAN_NAMES}

    print("# Part 3 tables (generated by make_tables_part3.py)\n")
    print("## McTiny: old session_s (part 1), new session_s, new network_s, start-up and key generation\n")
    print("Cells are median / p95 / max in seconds, n = 30 sessions. Start-up = median of (session_s - network_s) per session.\n")
    rows = []
    ratio_rows = []
    for name in WAN_NAMES:
        for cell in cell_order([k for k in new[name] if k.startswith("mctiny/")]):
            key = f"mctiny/{cell}"
            nrows = new[name][key]
            o = values(old[name].get(key, []), "session_s")
            s = values(nrows, "session_s")
            n = values(nrows, "network_s")
            startup = [r["session_s"] - r["network_s"] for r in nrows if r.get("ok") and r.get("network_s") is not None]
            fails = sum(1 for r in nrows if not r.get("ok"))
            rows.append([cell, len(s), stats3(o), stats3(s), stats3(n),
                         f"{st.median(startup):.3f} ({min(startup):.3f} to {max(startup):.3f})" if startup else "-", fails])
            hq = {}
            for system in ("stateless", "stateful"):
                src_new = values(new[name].get(f"{system}/{cell}", []), "session_s")
                src_old = values(old[name].get(f"{system}/{cell}", []), "session_s")
                hq[system] = (st.median(src_new) if src_new else None, st.median(src_old) if src_old else None)
            ratio_rows.append((name, cell, o, s, n, hq))
    table(["cell", "n ok", "old session_s", "new session_s", "new network_s", "start-up + keygen s", "failed"], rows)

    print("## Ratio McTiny / HqcLethe (medians, HQC-5)\n")
    print("HqcLethe `session_s` starts at the first request, so the fair McTiny figure is `network_s`. "
          "Old ratio = part 1 McTiny session_s / part 1 HqcLethe session_s. "
          "HqcLethe medians come from this run for the profile cells and from part 1 for the loss and GE cells (not rerun).\n")
    out = []
    for name, cell, o, s, n, hq in ratio_rows:
        if not n:
            continue
        mn = st.median(n)
        row = [cell]
        for system in ("stateless", "stateful"):
            new_med, old_med = hq[system]
            hqm = new_med if new_med is not None else old_med
            old_ratio = st.median(o) / old_med if o and old_med else None
            row += [f"{hqm:.3f}" if hqm else "-", f"{mn / hqm:.1f}" if hqm else "-", f"{old_ratio:.1f}" if old_ratio else "-"]
        out.append(row)
    table(["cell", "stateless median s", "net ratio", "old ratio", "stateful median s", "net ratio", "old ratio"], out)

    print("## HqcLethe profile cells: session_s against process_s\n")
    rows = []
    for key in sorted(new["wan_profiles"]):
        if key.startswith("mctiny/"):
            continue
        system, cell = key.split("/", 1)
        r = new["wan_profiles"][key]
        sess, proc = values(r, "session_s"), values(r, "process_s")
        rows.append([system, cell, len(sess), stats3(sess), stats3(proc), f"{st.median(proc) - st.median(sess):.3f}"])
    table(["system", "cell", "n", "session_s med / p95 / max", "process_s med / p95 / max", "median process - session"], rows)

    print(f"## McTiny tails: sessions with network_s above {TAIL_S:.0f} s (cap of one retransmission timeout: {CAP_S:.0f} s)\n")
    rows = []
    for name in WAN_NAMES:
        for key in sorted(new[name]):
            if not key.startswith("mctiny/"):
                continue
            for i, r in enumerate(new[name][key], 1):
                if r.get("ok") and r.get("network_s") and r["network_s"] > TAIL_S and r.get("stderr_file"):
                    rows.append(tail_report(dirs[name], name, key, i, r))
    table(["cell", "rep", "network_s", "packets sent", "packets received", "idle gaps (no packet at all) of 5 s or more"], rows)


if __name__ == "__main__":
    main()
